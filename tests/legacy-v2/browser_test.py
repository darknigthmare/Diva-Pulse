"""Real browser interaction checks, with a local-content fallback for restricted CI.
No browser policies are changed. set_content tests the app in an opaque origin:
IndexedDB persistence and physical download completion are NOT certified here.
Run under xvfb-run on Linux without an X display for software WebGL rendering.
"""
from playwright.sync_api import sync_playwright
from pathlib import Path
import json, time, traceback, os
R=Path(__file__).resolve().parents[1]; QA=R/'qa'; QA.mkdir(exist_ok=True)
checks=[]; errors=[]; console=[]; current='boot'
def check(name, assertion=True):
 assert assertion,name
 checks.append({'name':name,'passed':True}); print('PASS',name,flush=True)
def wait_idle(p):
 p.wait_for_function('window.PulseApp && !PulseApp.busy',timeout=20000)
def nav(p,v):
 p.locator(f'nav [data-view="{v}"]').click(); p.wait_for_function('(v)=>PulseApp.view===v',arg=v)
with sync_playwright() as tool:
 browser=tool.chromium.launch(executable_path=os.environ.get('CHROMIUM','/usr/bin/chromium'),headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
 p=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1,accept_downloads=True)
 p.set_default_timeout(10000)
 p.on('pageerror',lambda e:errors.append(str(e)))
 p.on('console',lambda m:console.append({'type':m.type,'text':m.text}) if m.type in ['error','warning'] else None)
 try:
  p.set_content((R/'DIVA_PULSE_JOUER.html').read_text(),wait_until='load')
  p.wait_for_function('document.documentElement.dataset.ready === "true"')
  check('Boot: three original songs and fifteen charts',p.evaluate('PulseApp.songs.length===3 && PulseApp.songs.every(s=>s.charts.length===5)'))
  check('Real WebGL2 context, shader and stage drawing',p.evaluate('PulseApp.stage.available && PulseApp.stage.gl.getError()===0'))
  p.mouse.click(30,190)
  # Capture exports in memory, not a bypass of browser download policy.
  p.evaluate('''() => {window.testDownloads=[]; PulseServices.download=(data,name,type)=>testDownloads.push({data,name,type});}''')
  nav(p,'wardrobe')
  p.locator('#castSlot').select_option('1');p.locator('#avatarGrid button').nth(1).click();wait_idle(p)
  p.locator('#castSlot').select_option('2');p.locator('#avatarGrid button').nth(2).click();wait_idle(p)
  p.locator('#costumeGrid button').nth(2).click();p.locator('#stageGrid button').nth(2).click()
  p.wait_for_timeout(120)
  check('Modules: trio, per-slot costume and sakura stage',p.evaluate('PulseApp.stage.rigs.length===3 && PulseApp.song.scene.cast.join(",")==="miku,rin,len" && PulseApp.song.scene.costumes[2]==="snow" && PulseApp.stage.stageId==="sakura"'))
  p.screenshot(path=str(QA/'02-modules-trio.png'),full_page=True)
  p.locator('#wardrobe summary').click()
  p.locator('#modelInput').set_input_files(str(R/'examples/MANNEQUIN_QA_ANIME.glb'));wait_idle(p)
  check('GLB: embedded skinned model and animation loaded',p.evaluate('PulseApp.stage.custom?.triangles===12 && PulseApp.stage.custom.clips.length===1'))
  check('GLB: animation changes joint rotation',p.evaluate('''()=>{let s=PulseApp.stage,c=s.custom;s.animateGLB(c,1);let q=JSON.stringify(c.nodes[1].q);s.animateGLB(c,3);return q!==JSON.stringify(c.nodes[1].q);}'''))
  p.locator('#clearModel').click();p.wait_for_function('!PulseApp.stage.custom')
  check('GLB: original cast restored after clearing import',p.evaluate('PulseApp.song.scene.modelAsset===null'))
  nav(p,'library')
  p.locator('#audioInput').set_input_files(str(R/'examples/CONTROLE_120_BPM.wav'));wait_idle(p)
  check('Audio import: decoded eight-second WAV, empty chart library',p.evaluate('PulseApp.songs.length===4 && Math.abs(PulseApp.song.duration-8)<.01 && PulseApp.song.charts.length===0'))
  check('No chart: play disabled rather than inventing a level',p.locator('#playButton').is_disabled())
  p.locator('#chartInput').set_input_files(str(R/'examples/CONTROLE_120_BPM.json'));wait_idle(p)
  check('Native chart import: all fifteen notes unchanged',p.evaluate('PulseApp.chart.notes.length===15 && PulseApp.chart.notes[6].time===3.25 && PulseApp.chart.notes[1].lane===3'))
  orig=p.evaluate('({id:PulseApp.chart.id,sig:PulseCore.chartSignature(PulseApp.chart)})')
  p.locator('#lyricsInput').set_input_files(str(R/'examples/CONTROLE_120_BPM.lrc'))
  p.wait_for_function('PulseApp.song.lyrics.length===5')
  check('LRC: synchronized local lyrics imported')
  p.locator('#autoButton').click();p.wait_for_function('PulseApp.view==="game" && !PulseApp.busy')
  p.wait_for_timeout(400);p.locator('#pauseButton').click();p.wait_for_function('PulseApp.paused')
  t=p.evaluate('PulseApp.audio.time');p.wait_for_timeout(220)
  check('Pause: audio clock is frozen',abs(p.evaluate('PulseApp.audio.time')-t)<.001)
  p.locator('#resumeGame').click();p.wait_for_function('!PulseApp.paused')
  p.wait_for_function('PulseApp.audio.time>1.6');p.screenshot(path=str(QA/'03-live.png'))
  p.wait_for_function('PulseApp.view==="results"',timeout=15000)
  check('Complete real-time Autoplay: 15/15 COOL and 100%',p.evaluate('PulseApp.lastResult.counts.COOL===15 && PulseApp.lastResult.accuracy===100 && PulseApp.lastResult.fullCombo'))
  check('Autoplay never creates a record',p.evaluate('PulseApp.scores.length===0'))
  p.screenshot(path=str(QA/'04-resultats.png'),full_page=True)
  p.locator('#resultEdit').click();p.wait_for_function('PulseApp.view==="editor"')
  box=p.locator('#timeline').bounding_box();p.mouse.click(box['x']+43+(box['width']-43)*.625/8,box['y']+75+(box['height']-75)/12)
  check('Manual editor: click adds an independent note',p.evaluate('PulseApp.editor.chart.notes.length===16'))
  p.locator('#noteX').fill('0.321');p.locator('#noteX').press('Tab')
  check('Manual editor: target position changed precisely',abs(p.evaluate('PulseApp.editor.note.x')-.321)<1e-8)
  p.locator('#undoButton').click();check('Manual editor: undo',p.evaluate('PulseApp.editor.note.x!==.321'))
  p.locator('#redoButton').click();check('Manual editor: redo',p.evaluate('PulseApp.editor.note.x===.321'))
  p.locator('#editorSave').click();wait_idle(p)
  check('Edited imports saved as new versions, source intact',p.evaluate('(o)=>PulseApp.song.charts.length===2 && PulseCore.chartSignature(PulseApp.song.charts.find(c=>c.id===o.id))===o.sig && PulseApp.editor.chart.source==="manual-derived"',orig))
  p.locator('#eventTime').fill('5');p.locator('#eventCamera').select_option('close');p.locator('#eventDance').select_option('reach');p.locator('#eventStage').select_option('orbital');p.locator('#addEventButton').click()
  check('PV director: timed camera, dance and stage event saved',p.evaluate('PulseApp.song.scene.events.some(e=>e.time===5 && e.camera==="close" && e.dance==="reach" && e.stage==="orbital")'))
  p.locator('#editorExport').click()
  check('JSON export action serializes chart, scene and lyrics',p.evaluate('(()=>{const d=JSON.parse(testDownloads.at(-1).data);return d.notes.length===16&&d.scene.events.length===3&&d.lyrics.length===5;})()'))
  p.screenshot(path=str(QA/'05-studio.png'),full_page=True)
  nav(p,'library')
  p.locator('#generateButton').click();p.locator('#genStart').click();wait_idle(p)
  check('Actual audio worker creates five additional chart difficulties',p.evaluate('PulseApp.song.charts.length===7 && PulseApp.song.charts.filter(c=>c.source==="generated").length===5'))
  check('Generation does not overwrite the original chart',p.evaluate('(o)=>PulseCore.chartSignature(PulseApp.song.charts.find(c=>c.id===o.id))===o.sig',orig))
  p.locator('#chartInput').set_input_files(str(R/'examples/CONTROLE_SYNTHETIQUE_FT.dsc'));wait_idle(p)
  check('Binary DSC import through UI preserves timing and chord mapping',p.evaluate('PulseApp.chart.source==="dsc"&&PulseApp.chart.notes.length===7&&PulseApp.chart.notes[0].time===1'))
  p.locator('#audioInput').set_input_files(str(R/'examples/CONTROLE_120_BPM.wav'));wait_idle(p)
  check('Reimporting exact audio file reuses song and charts',p.evaluate('PulseApp.songs.length===4&&PulseApp.song.charts.length===8'))
  # Bad payload must preserve the current library.
  p.locator('#chartInput').set_input_files({'name':'invalid.json','mimeType':'application/json','buffer':b'{"notes":[{"time":-1,"lane":0}]}' });wait_idle(p)
  check('Malformed import: friendly error, library unchanged',p.evaluate('PulseApp.song.charts.length===8&&document.getElementById("toast").classList.contains("error")'))
  nav(p,'settings');p.locator('#exportLibrary').click();wait_idle(p)
  pack=p.evaluate('testDownloads.at(-1).data');data=json.loads(pack)
  check('Library export contains all songs and original media',data['format']=='DIVA-PULSE-LIBRARY' and len(data['songs'])==4 and len(data['assets'])>=2)
  (QA/'test-backup.pulsepack').write_text(pack)
  p.locator('#backupInput').set_input_files({'name':'backup.pulsepack','mimeType':'application/json','buffer':pack.encode()});wait_idle(p)
  check('Library restore creates copies without overwriting originals',p.evaluate('PulseApp.songs.length===8 && new Set(PulseApp.songs.map(s=>s.id)).size===8'))
  p.locator('#showTouch').check();check('Tactile setting stored',p.evaluate('PulseApp.settings.showTouch===true'))
  nav(p,'library');p.locator('#searchSongs').fill('GLASS ORBIT')
  check('Search filters the visible song library',p.locator('#songList .song-card').count()==2)
  p.locator('#searchSongs').fill('');p.locator('#songList .song-card').nth(0).click();p.wait_for_timeout(100)
  p.evaluate('document.getElementById("toast").hidden=true')
  p.screenshot(path=str(QA/'01-accueil.png'),full_page=True)
  p.set_viewport_size({'width':390,'height':844});p.wait_for_timeout(200)
  check('Mobile portrait has no horizontal page overflow',p.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'))
  p.screenshot(path=str(QA/'06-mobile.png'),full_page=True)
  p.set_viewport_size({'width':844,'height':390});p.wait_for_timeout(200)
  check('Mobile landscape has no horizontal page overflow',p.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'))
  p.screenshot(path=str(QA/'07-paysage.png'),full_page=True)
  check('No uncaught JS or rendering errors in all tested flows',not errors and p.evaluate('!PulseApp.frameError'))
 except Exception as ex:
  checks.append({'name':'Workflow interruption after '+str(len(checks))+' checks','passed':False,'error':str(ex)})
  print(traceback.format_exc());p.screenshot(path=str(QA/'failure.png'),full_page=True)
 finally:
  result={'environment':'Chromium 144 Linux / Playwright / Xvfb + SwiftShader / set_content (opaque origin)','checks':checks,'passed':sum(c['passed'] for c in checks),'failed':sum(not c['passed'] for c in checks),'uncaughtErrors':errors,'console':console,'notValidated':['HTTP or file navigation blocked by host browser policy','Persistent IndexedDB across reloads (opaque test origin)','Actual file download completion (serialization captured)','Physical gamepads, touch devices and Bluetooth latency','Safari, Firefox and Android browsers']}
  (QA/'browser-results.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
  print('RESULT',result['passed'], 'passed /',result['failed'],'failed. JS errors:',errors,flush=True)
  browser.close()
